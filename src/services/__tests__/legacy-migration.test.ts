import { mkdir, mkdtemp, rm, writeFile } from 'fs/promises';
import { existsSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import { findLegacyOutputs, removeLegacyOutputs } from '../legacy-migration.js';

describe('legacy aicgen 1.x output migration', () => {
  let dir: string;

  beforeEach(async () => {
    dir = await mkdtemp(join(tmpdir(), 'aicgen-legacy-'));
  });

  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  const write = async (relative: string, content: string) => {
    const full = join(dir, relative);
    await mkdir(join(full, '..'), { recursive: true });
    await writeFile(full, content, 'utf-8');
    return full;
  };

  it('finds the Claude guidelines folder', async () => {
    await write('.claude/guidelines/language.md', '# Language');
    expect(await findLegacyOutputs(dir, 'claude-code')).toEqual([join(dir, '.claude/guidelines')]);
  });

  it('only matches Copilot files that look aicgen-generated', async () => {
    const generated = await write('.github/instructions/security.instructions.md', '---\napplyTo: "**/*"\ndescription: "Security guidelines"\n---\n');
    await write('.github/instructions/security-team.instructions.md', '---\napplyTo: "**/*"\ndescription: "Security guidelines"\n---\n');
    await write('.github/instructions/testing.instructions.md', '---\napplyTo: "**/*.ts"\ndescription: "my own testing notes"\n---\n');

    expect(await findLegacyOutputs(dir, 'copilot')).toEqual([generated]);
  });

  it('finds the 1.x Copilot chat mode and the undocumented Codex instructions file', async () => {
    const chatMode = await write('.github/chatmodes/aicgen-review.chatmode.md', '---\n---\n');
    const codex = await write('.codex/instructions.md', '# Codex\n\n*Generated by aicgen*\n');
    await write('.codex/config.toml', 'model = "x"');

    expect(await findLegacyOutputs(dir, 'copilot')).toEqual([chatMode]);
    expect(await findLegacyOutputs(dir, 'codex')).toEqual([codex]);
  });

  it('finds Antigravity .agent rules by marker and known workflow names only', async () => {
    const rule = await write('.agent/rules/security.md', '# Security\n\n*Generated by aicgen*\n');
    await write('.agent/rules/mine.md', '# my rule');
    const workflow = await write('.agent/workflows/spec.md', 'x');
    await write('.agent/workflows/deploy.md', 'x');

    expect((await findLegacyOutputs(dir, 'antigravity')).sort()).toEqual([rule, workflow].sort());
  });

  it('removes only the listed paths', async () => {
    const generated = await write('.agent/rules/security.md', '*Generated by aicgen*');
    const mine = await write('.agent/rules/mine.md', '# my rule');

    await removeLegacyOutputs(await findLegacyOutputs(dir, 'antigravity'));

    expect(existsSync(generated)).toBe(false);
    expect(existsSync(mine)).toBe(true);
  });

  it('finds nothing in a clean project', async () => {
    for (const assistant of ['claude-code', 'copilot', 'antigravity', 'codex'] as const) {
      expect(await findLegacyOutputs(dir, assistant)).toEqual([]);
    }
  });
});
