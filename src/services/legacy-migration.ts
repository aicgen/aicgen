import { readdir, readFile, rm } from 'fs/promises';
import { join } from 'path';
import { AIAssistant } from '../models/project.js';
import { exists } from '../utils/file.js';

/**
 * aicgen 1.x inlined every guideline of a category into one large always-on file.
 * 2.0 delivers one small file per guideline (path-scoped rules and skills), so the
 * old category files would load the same content a second time. These helpers find
 * the 1.x outputs so generation can replace them. Only files that carry aicgen's
 * own markers are touched; user-authored files are never removed.
 */

const LEGACY_CATEGORY_SLUGS = new Set([
  'api-design', 'architecture', 'best-practices', 'code-style', 'database',
  'design-patterns', 'devops', 'error-handling', 'general', 'language',
  'performance', 'security', 'testing',
]);

const LEGACY_WORKFLOW_NAMES = new Set([
  'spec', 'research', 'plan', 'build', 'check', 'ship',
  'generate-unit-tests', 'add-documentation', 'refactor-extract-module',
  'generate-integration-tests', 'security-audit', 'performance-audit',
]);

async function listFiles(dir: string): Promise<string[]> {
  try {
    return await readdir(dir);
  } catch {
    return [];
  }
}

export async function findLegacyOutputs(projectPath: string, assistant: AIAssistant): Promise<string[]> {
  const found: string[] = [];

  switch (assistant) {
    case 'claude-code': {
      // .claude/guidelines/ was entirely generated by aicgen 1.x
      const dir = join(projectPath, '.claude', 'guidelines');
      if (await exists(dir)) found.push(dir);
      break;
    }

    case 'copilot': {
      // Chat modes were renamed to custom agents (.github/agents/*.agent.md)
      const chatMode = join(projectPath, '.github', 'chatmodes', 'aicgen-review.chatmode.md');
      if (await exists(chatMode)) found.push(chatMode);

      // Prompt files and the always-on workflows instruction file were replaced by skills
      const promptsDir = join(projectPath, '.github', 'prompts');
      for (const name of await listFiles(promptsDir)) {
        if (!name.endsWith('.prompt.md') || !LEGACY_WORKFLOW_NAMES.has(name.replace(/\.prompt\.md$/, ''))) continue;
        const content = await readFile(join(promptsDir, name), 'utf-8');
        if (content.includes('Follow the generated repository instructions and scoped instruction files')) {
          found.push(join(promptsDir, name));
        }
      }
      const workflowsInstructions = join(projectPath, '.github', 'instructions', 'workflows.instructions.md');
      if (await exists(workflowsInstructions) &&
          (await readFile(workflowsInstructions, 'utf-8')).includes('description: "SDLC workflow slash commands"')) {
        found.push(workflowsInstructions);
      }

      const dir = join(projectPath, '.github', 'instructions');
      for (const name of await listFiles(dir)) {
        const slug = name.replace(/\.instructions\.md$/, '');
        if (!name.endsWith('.instructions.md') || !LEGACY_CATEGORY_SLUGS.has(slug)) continue;
        const content = await readFile(join(dir, name), 'utf-8');
        if (/^description: ".+ guidelines"$/m.test(content)) found.push(join(dir, name));
      }
      break;
    }

    case 'antigravity': {
      const rules = join(projectPath, '.agent', 'rules');
      for (const name of await listFiles(rules)) {
        if (!name.endsWith('.md')) continue;
        const content = await readFile(join(rules, name), 'utf-8');
        if (content.includes('*Generated by aicgen*')) found.push(join(rules, name));
      }
      const workflows = join(projectPath, '.agent', 'workflows');
      for (const name of await listFiles(workflows)) {
        if (name.endsWith('.md') && LEGACY_WORKFLOW_NAMES.has(name.replace(/\.md$/, ''))) {
          found.push(join(workflows, name));
        }
      }
      break;
    }

    case 'codex': {
      // .codex/instructions.md is not a documented Codex file; 2.0 keeps everything in AGENTS.md
      const file = join(projectPath, '.codex', 'instructions.md');
      if (await exists(file) && (await readFile(file, 'utf-8')).includes('*Generated by aicgen*')) {
        found.push(file);
      }
      break;
    }
  }

  return found;
}

export async function removeLegacyOutputs(paths: string[]): Promise<void> {
  for (const path of paths) {
    await rm(path, { recursive: true, force: true });
  }
}
